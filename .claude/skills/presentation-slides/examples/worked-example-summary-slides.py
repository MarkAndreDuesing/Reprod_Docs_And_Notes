def clear_body(s):
    for sh in list(s.shapes):
        if sh.is_placeholder: continue
        if sh.has_text_frame and sh.text_frame.text.strip() in ('…',): sh._element.getparent().remove(sh._element)
def title(s,t):
    tb=s.shapes.add_textbox(Inches(.7),Inches(.4),Inches(11.93),Inches(.9))
    tb.text_frame.paragraphs[0].alignment=PP_ALIGN.LEFT; r=tb.text_frame.paragraphs[0].add_run(); r.text=t; f=r.font; f.size=Pt(40); f.bold=True; f.name='Arial'; f.color.rgb=G
def new(t):
    s=p.slides.add_slide(base)
    for ph in list(s.placeholders): ph._element.getparent().remove(ph._element)
    el=copy.deepcopy(title_el); s.shapes._spTree.append(el)
    sh=s.shapes[-1]; sh.text_frame.paragraphs[0].runs[0].text=t
    s.shapes._spTree.append(copy.deepcopy(numph)); return s
import re as _re
def strip(t): return _re.sub(r'\s*\((?:p|pp|Table|Fig)\.?\s[^)]*\)','',t)
def tb(s,x,y,w,h,paras,size=18,anchor=None,align=None,space=6):
    """paras: list of paragraphs; each paragraph = list of runs (text, dict)"""
    box=s.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h)); tf=box.text_frame; tf.word_wrap=True
    if anchor: tf.vertical_anchor=anchor
    for i,runs in enumerate(paras):
        para=tf.paragraphs[0] if i==0 else tf.add_paragraph()
        para.space_after=Pt(space)
        if align: para.alignment=align
        if isinstance(runs,str): runs=[(runs,{})]
        for txt,o in runs:
            r=para.add_run(); r.text=strip(txt); f=r.font; f.name='Arial'
            f.size=Pt(o.get('size',size)); f.bold=o.get('b',False); f.italic=o.get('i',False)
            f.color.rgb=o.get('c',K)
    return box
def panel(s,x,y,w,h,fill=PANEL,line=None):
    sh=s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE,Inches(x),Inches(y),Inches(w),Inches(h))
    sh.adjustments[0]=0.08; sh.fill.solid(); sh.fill.fore_color.rgb=fill
    if line: sh.line.color.rgb=line; sh.line.width=Pt(1.25)
    else: sh.line.fill.background()
    sh.shadow.inherit=False; return sh
def label(s,t): tb(s,.7,1.2,10,.4,[[(t,{'c':M,'size':16,'b':True})]])
def notes(s,t): s.notes_slide.notes_text_frame.text=t
def B(t,**o): return (t,dict(b=True,**o))
def N(t,**o): return (t,dict(**o))

